from __future__ import annotations

import csv
import json
import math
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CSV_PATH = HERE / "CSVdataPendudukISPA.csv"
OUTPUT_PATH = HERE.parent / "data" / "insiden_ispa_2025.js"

# These map names differ from the verified kelurahan names in the source CSV.
NAME_ALIASES = {
    "halimperdanakusuma": "halimperdanakusumah",
    "krendang": "kerendang",
    "pangadegan": "pengadegan",
    "panggilingan": "penggilingan",
    "petegogan": "petogogan",
    "tanahsareal": "tanahsereal",
    "utankayutimur": "utankayuselatan",
}
REQUIRED_COLUMNS = {
    "kelurahan",
    "kecamatan",
    "kota_adm",
    "penduduk_total",
    "pasien_ispa_2025",
    "insiden_ispa_per1000",
}


def normalize_name(value: str) -> str:
    return re.sub(r"[^a-z0-9]", "", value.casefold())


def load_records() -> dict[str, dict[str, str | int | float]]:
    with CSV_PATH.open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source)
        missing_columns = REQUIRED_COLUMNS - set(reader.fieldnames or ())
        if missing_columns:
            raise ValueError(f"Kolom CSV tidak ditemukan: {sorted(missing_columns)}")

        records: dict[str, dict[str, str | int | float]] = {}
        for row in reader:
            name = (row["kelurahan"] or "").strip()
            key = normalize_name(name)
            if not key:
                raise ValueError("CSV memuat nama kelurahan kosong.")
            if key in records:
                raise ValueError(f"Nama kelurahan ganda setelah normalisasi: {name}")

            population = int(row["penduduk_total"])
            cases = int(row["pasien_ispa_2025"])
            rate = float(row["insiden_ispa_per1000"])
            if population <= 0 or cases < 0 or not math.isfinite(rate):
                raise ValueError(f"Data populasi, kasus, atau insiden tidak valid: {name}")

            calculated_rate = cases / population * 1000
            if abs(calculated_rate - rate) > 0.02:
                raise ValueError(f"Insiden tidak sesuai kasus/populasi: {name}")

            records[key] = {
                "kelurahan": name,
                "kecamatan": row["kecamatan"].strip(),
                "kota": row["kota_adm"].strip(),
                "population": population,
                "cases": cases,
                "per1000": rate,
            }

    if not records:
        raise ValueError(f"Tidak ada data kelurahan di {CSV_PATH}")

    for alias, target in NAME_ALIASES.items():
        if alias in records:
            raise ValueError(f"Alias bertabrakan dengan nama CSV: {alias}")
        if target not in records:
            raise ValueError(f"Tujuan alias tidak ada di CSV: {alias} -> {target}")
        records[alias] = records[target]

    return records


def main() -> None:
    records = load_records()
    data = {
        "year": 2025,
        "source": "https://dinkes.jakarta.go.id/",
        "records": records,
    }
    generated = (
        "// Generated by Others/generate_insiden_ispa_js.py; do not edit by hand.\n"
        "window.ispaIncidence2025 = "
        + json.dumps(data, ensure_ascii=False, indent=2)
        + ";\n"
    )
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(generated, encoding="utf-8")
    print(f"Generated {OUTPUT_PATH} with {len(records) - len(NAME_ALIASES)} kelurahan "
          f"and {len(NAME_ALIASES)} map-name aliases.")


if __name__ == "__main__":
    main()
